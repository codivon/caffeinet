    public function render(SettingsService $settings, WorkingHoursService $workHours): \Illuminate\View\View
    {
        /* متن معرفی — خالی → پیش‌فرض کد */
        $intro = trim((string) $settings->get('about.intro', ''));
        if ($intro === '') {
            $intro = self::DEFAULT_INTRO;
        }

        /* سوالات متداول — تنظیمات json آرایهٔ {q,a} است؛ خراب/خالی → پیش‌فرض کد */
        $faqItems = $this->normalizeFaq($settings->get('about.faq'));
        if ($faqItems === []) {
            $faqItems = $this->normalizeFaq(self::DEFAULT_FAQ);
        }

        $wh = $workHours->status();
        $workStatus = [
            'enabled'  => $wh['enabled'],
            'open'     => $wh['open'],
            'today'    => $wh['day_today_open'],
            'range'    => fa_digits($wh['start']).' تا '.fa_digits($wh['end']),
            'message'  => $wh['message'],
        ];

        return view('livewire.front.about', [
            'intro'      => $intro,
            'faqItems'   => $faqItems,
            'workStatus' => $workStatus, // ویوی کامپوننت (پیل ساعت کاری هیرو) هم از این می‌خواند — عین Landing
        ])->layoutData([
            // هدر/فوتر لایهٔ لندینگ به این داده‌ها نیاز دارند (عین StatusBoard)
            'workStatus'        => $workStatus,
            'landingCategories' => collect(),
            'footerCategories'  => collect(),
            'htmlTitle'         => __('chrome.about.html_title'),
            'pageTitle'         => __('chrome.about.hero_badge'),
        ]);
    }

    /**
     * نرمال‌سازی FAQ: آرایهٔ {q,a} → فهرست تمیز رشته‌ها؛ ورودی خراب حذف می‌شود.
     *
     * @param  mixed  $raw  آرایهٔ ذخیره‌شده در تنظیمات (json) یا پیش‌فرض کد
     * @return list<array{q: string, a: string}>
     */
    private function normalizeFaq(mixed $raw): array
    {
        if (! is_array($raw)) {
            return [];
        }

        $items = [];
        foreach ($raw as $row) {
            $q = is_array($row) ? trim((string) ($row['q'] ?? '')) : '';
            $a = is_array($row) ? trim((string) ($row['a'] ?? '')) : '';

            if ($q === '' || $a === '') {
                continue;
            }

            $items[] = ['q' => $q, 'a' => $a];
        }

        return $items;
    }
}
